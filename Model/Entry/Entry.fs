namespace DrizzleCarton.Model

// TODO: implement invariant protections in the module
type EntryId = private EntryId of int // generated by the database
type EntryName = private EntryName of string
type EntryParent = private EntryParent of Option<int> // may only be None for the root folder
type EntryKind = private EntryKind of string // must be "folder" or "file"
type EntrySize = private EntrySize of int // must be greater than or equal to 0. Folders always have a size of 0.

[<RequireQualifiedAccess>]
module EntryId =
  let ofRaw id =
    if id < 1 then None else Some <| EntryId id

  let toRaw (EntryId(eid)) = eid

  let first = EntryId 1

[<RequireQualifiedAccess>]
module EntryName =
  let ofRaw (name: string) =
    name
    |> Validation.nonEmpty "Entry name may not be empty."
    |> Result.bind (fun n ->
      if n.Length > 64 then
        Error "Entry name may not be longer than 64 characters."
      else
        Ok n)
    |> Result.bind (Validation.noForwardSlashes "Entry name may not contain forward slashes.")
    |> Result.bind (Validation.noBackwardSlashes "Entry name may not contain backward slashes.")
    |> Result.map EntryName

  let toRaw (EntryName(name)) = name

[<RequireQualifiedAccess>]
module EntryParent =
  let ofRaw parent = EntryParent parent

  let toRaw (EntryParent(parent)) = parent

[<RequireQualifiedAccess>]
module EntryKind =
  let ofRaw kind = EntryKind kind

  let toRaw (EntryKind(kind)) = kind

[<RequireQualifiedAccess>]
module EntrySize =
  let ofRaw size = EntrySize size

  let toRaw (EntrySize(size)) = size

type Entry =
  { Id: EntryId
    Name: EntryName
    Parent: EntryParent
    Kind: EntryKind
    Size: EntrySize }

module Entry =
  let toEntry (id, name, parent, kind, size) : Entry =
    { Id = id
      Name = name
      Parent = parent
      Kind = kind
      Size = size }
