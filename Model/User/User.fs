namespace DrizzleCarton.Model

type UserId = private UserId of int // generated by database when adding user
type UserName = private UserName of string
type UserQuota = private UserQuota of int
type UserRoot = private UserRoot of EntryId

module UserId =
  let ofRaw id =
    if id < 1 then
      Error "User id may not be less than 1."
    else
      Ok <| UserId id

  let toRaw (UserId(id)) = id

  let first = UserId 1

module UserName =
  let ofRaw name =
    name
    |> Validation.nonEmpty "User name may not be empty"
    |> Result.bind (Validation.noSpaces "User name may not contain spaces.")
    |> Result.bind (fun n ->
      if n.Contains "drizzle" || n.Contains "carton" then
        Error "User name may not contain the words 'drizzle' or 'carton'."
      else
        Ok n)
    |> Result.map UserName

  let toRaw (UserName(name)) = name

module UserQuota =
  let minimum = 1024 * 1024

  let ofRaw quota =
    quota
    |> Validation.nonNegativeNumber "User quota may not be a negative number."
    |> Result.bind (fun q ->
      if q < minimum then
        Error "User quota must be at least 1024 * 1024 (1 megabyte)."
      else
        Ok q)
    |> Result.map UserQuota

  let toRaw (UserQuota(quota)) = quota

// must be the identifier of a folder with the name "files" that has no parent entry
module UserRoot =
  let ofRaw id =
    id |> EntryId.ofRaw |> Result.map UserRoot

  let toRaw (UserRoot(id)) = id

module User =

  type User =
    private
      { Id: UserId
        Username: UserName
        Quota: UserQuota
        RootFolder: UserRoot }

  let toUser (id, username, quota, rootFolder) : User =
    { Id = UserId id
      Username = UserName username
      Quota = UserQuota quota
      RootFolder = UserRoot rootFolder }

  let toTuple (user: User) =
    user.Id, user.Username, user.Quota, user.RootFolder
