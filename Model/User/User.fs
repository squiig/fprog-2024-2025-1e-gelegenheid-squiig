namespace DrizzleCarton.Model

// TODO: implement invariant protections in the module
type UserId = private UserId of int // generated by database when adding user
type UserName = private UserName of string // may not contain spaces, may not include the text "drizzle" or "carton"
type UserQuota = private UserQuota of int // must be a positive number greater than 1024 * 1024 (1 megabyte)
type UserRoot = private UserRoot of int // must be the identifier of a folder with the name "files" that has no parent entry

type User =
  { Id: UserId
    Username: UserName
    Quota: UserQuota
    RootFolder: UserRoot }

module User =
  let toUser (id, username, quota, rootFolder) : User =
    { Id = UserId id
      Username = UserName username
      Quota = UserQuota quota
      RootFolder = UserRoot rootFolder }

  let toTuple (user: User) =
    user.Id, user.Username, user.Quota, user.RootFolder
